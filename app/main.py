from pathlib import Path

from fastapi import BackgroundTasks, Depends, FastAPI, HTTPException
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session

from app.database import Base, engine, get_db
from app.models import GenerationJob, Certificate
from app.schemas import GenerationJobCreate, GenerationJobResponse, CertificateResponse, JobStatusResponse
from app.services.job_processor import process_generation_job

Base.metadata.create_all(bind=engine)

app = FastAPI(
    title="Bulk Certificate Generator API",
    version="1.0.0",
    description="API for bulk certificate generation and status tracking.",
)


@app.get("/health")
def health():
    return {"status": "ok"}


@app.post(
    "/api/v1/jobs",
    response_model=GenerationJobResponse,
    status_code=202,
    summary="Create a certificate generation job",
)
def create_job(
    payload: GenerationJobCreate,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
):
    job = GenerationJob(
        course_name=payload.course_name,
        issuer_name=payload.issuer_name,
        issue_date=payload.issue_date,
        status="pending",
        total=len(payload.recipients),
        success_count=0,
        failure_count=0,
    )
    db.add(job)
    db.flush()

    for recipient in payload.recipients:
        db.add(
            Certificate(
                job_id=job.id,
                recipient_name=recipient.name,
                recipient_email=recipient.email,
                status="pending",
            )
        )

    db.commit()
    db.refresh(job)

    # The API returns immediately; generation happens after the response.
    background_tasks.add_task(process_generation_job, job.id)

    return job


@app.get(
    "/api/v1/jobs/{job_id}",
    response_model=JobStatusResponse,
    summary="Get job status and progress",
)
def get_job(job_id: str, db: Session = Depends(get_db)):
    job = db.query(GenerationJob).filter(GenerationJob.id == job_id).first()
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")

    certificates = (
        db.query(Certificate)
        .filter(Certificate.job_id == job_id)
        .order_by(Certificate.created_at.asc())
        .all()
    )

    return {
        "job": job,
        "progress_percent": round(
            ((job.success_count + job.failure_count) / job.total) * 100, 2
        ) if job.total else 100,
        "certificates": certificates,
    }


@app.get(
    "/api/v1/jobs/{job_id}/certificates",
    response_model=list[CertificateResponse],
    summary="List certificates generated by a job",
)
def list_certificates(job_id: str, db: Session = Depends(get_db)):
    job = db.query(GenerationJob).filter(GenerationJob.id == job_id).first()
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")

    return (
        db.query(Certificate)
        .filter(Certificate.job_id == job_id)
        .order_by(Certificate.created_at.asc())
        .all()
    )


@app.get(
    "/api/v1/certificates/{certificate_id}",
    summary="Download a generated certificate",
)
def download_certificate(certificate_id: str, db: Session = Depends(get_db)):
    certificate = (
        db.query(Certificate)
        .filter(Certificate.id == certificate_id)
        .first()
    )

    if not certificate:
        raise HTTPException(status_code=404, detail="Certificate not found")

    if certificate.status != "success" or not certificate.file_path:
        raise HTTPException(
            status_code=409,
            detail="Certificate is not available because generation did not succeed",
        )

    if not Path(certificate.file_path).is_file():
        raise HTTPException(
            status_code=410,
            detail="Certificate was generated but its file is no longer available",
        )

    return FileResponse(
        certificate.file_path,
        media_type="application/pdf",
        filename=f"{certificate.recipient_name.replace(' ', '_')}_certificate.pdf",
    )
